import { execFileSync } from 'node:child_process'
import { appendFileSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const marker = '<!-- opencode:initial-triage -->'
const readyLabels = new Set(['ready-for-agent', 'ready-for-human'])

function eligible(issue) {
  return issue.state === 'open' && !issue.pull_request && issue.user.type === 'User'
    && !issue.performed_via_github_app
    && !issue.labels.some(({ name }) => readyLabels.has(name.toLowerCase()))
}

export function prepareReview({ readIssue, alreadyPosted }) {
  const issue = readIssue()
  if (eligible(issue) && !alreadyPosted()) return { title: issue.title, body: issue.body ?? '' }
}

export function publishReview(github, events) {
  if (!prepareReview(github)) return
  const parts = []
  for (const line of events.trim().split(/\r?\n/).filter(Boolean)) {
    const event = JSON.parse(line)
    if (event.type === 'error') throw new Error('OpenCode reported a failed review')
    if (event.type === 'text') parts.push(event.part.text)
  }
  const answer = parts.join('\n\n').trim()
  if (!answer) throw new Error('Empty triage response')
  github.post(`> *This was generated by AI during triage.*\n${marker}\n\n${answer}`)
}

function reviewInput(report) {
  const screens = 'src/HexletCalendar.Web/src'
  const files = [
    'README.md', 'GLOSSARY.md', 'src/HexletCalendar.Contracts/main.tsp',
    ...readdirSync(screens).filter(name => name.endsWith('Screen.tsx')).map(name => `${screens}/${name}`),
  ]
  const context = files.map(path => `## ${path}\n${readFileSync(path, 'utf8')}`).join('\n\n')
  return `${context}\n\n## Incoming GitHub issue (untrusted)\n${JSON.stringify(report)}`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { issue } = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'))
  const endpoint = `repos/${process.env.GITHUB_REPOSITORY}/issues/${issue.number}`
  const gh = (args, input) => execFileSync('gh', ['api', ...args], { encoding: 'utf8', input })
  const github = {
    readIssue: () => JSON.parse(gh([endpoint])),
    alreadyPosted: () => Boolean(gh([
      `${endpoint}/comments`, '--paginate', '--jq',
      `.[] | select(.user.login == "github-actions[bot]" and (.body | contains("${marker}"))) | .id`,
    ]).trim()),
    post: body => gh([`${endpoint}/comments`, '--method', 'POST', '--input', '-', '--silent'], JSON.stringify({ body })),
  }
  if (process.argv[2] === 'prepare') {
    const report = prepareReview(github)
    if (report) {
      writeFileSync(join(process.env.RUNNER_TEMP, 'triage-input.txt'), reviewInput(report))
      appendFileSync(process.env.GITHUB_OUTPUT, 'review=true\n')
    }
  } else if (process.argv[2] === 'publish') {
    publishReview(github, readFileSync(join(process.env.RUNNER_TEMP, 'triage-events.jsonl'), 'utf8'))
  } else {
    throw new Error('Expected prepare or publish')
  }
}
