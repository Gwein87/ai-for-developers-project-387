import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

const marker = '<!-- opencode:initial-triage -->'
const readyLabels = new Set(['ready-for-agent', 'ready-for-human'])

function eligible(issue) {
  return issue.state === 'open' && !issue.pull_request && issue.user.type === 'User'
    && !issue.performed_via_github_app
    && !issue.labels.some(({ name }) => readyLabels.has(name.toLowerCase()))
}

export async function triage({ readIssue, alreadyPosted, review, post }) {
  const issue = readIssue()
  if (!eligible(issue) || alreadyPosted()) return
  const result = await review({ title: issue.title, body: issue.body ?? '' })
  if (typeof result !== 'string' || !result.trim()) throw new Error('Empty triage response')
  if (eligible(readIssue()) && !alreadyPosted()) {
    post(`> *This was generated by AI during triage.*\n${marker}\n\n${result.trim()}`)
  }
}

async function review(report) {
  const screens = 'src/HexletCalendar.Web/src'
  const files = [
    'README.md', 'GLOSSARY.md', 'src/HexletCalendar.Contracts/main.tsp',
    ...readdirSync(screens).filter(name => name.endsWith('Screen.tsx')).map(name => `${screens}/${name}`),
  ]
  const context = files.map(path => `## ${path}\n${readFileSync(path, 'utf8')}`).join('\n\n')
  const response = await fetch('https://opencode.ai/inference/openai/v1/chat/completions', {
    method: 'POST',
    headers: { Authorization: `Bearer ${process.env.OPENCODE_API_KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: 'deepseek-v4.1-flash-free',
      messages: [
        { role: 'system', content: `${process.env.TRIAGE_PROMPT}\n\n${context}` },
        { role: 'user', content: JSON.stringify(report) },
      ],
    }),
    signal: AbortSignal.timeout(180_000),
  })
  if (!response.ok) throw new Error(`OpenCode returned HTTP ${response.status}`)
  return (await response.json()).choices?.[0]?.message?.content
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { issue } = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'))
  const endpoint = `repos/${process.env.GITHUB_REPOSITORY}/issues/${issue.number}`
  const gh = (args, input) => execFileSync('gh', ['api', ...args], { encoding: 'utf8', input })
  await triage({
    readIssue: () => JSON.parse(gh([endpoint])),
    alreadyPosted: () => Boolean(gh([
      `${endpoint}/comments`, '--paginate', '--jq',
      `.[] | select(.user.login == "github-actions[bot]" and (.body | contains("${marker}"))) | .id`,
    ]).trim()),
    review,
    post: body => gh([`${endpoint}/comments`, '--method', 'POST', '--input', '-', '--silent'], JSON.stringify({ body })),
  })
}
